function chamfer(body) {
  return body.replace(/<rect x='([\d.]+)' y='([\d.]+)' width='([\d.]+)' height='([\d.]+)'(?: rx='[\d.]+')?( [^>]*)?\/>/g, (m, x, y, w, h, rest = "") => {
    [x, y, w, h] = [x, y, w, h].map(Number);
    const c = Math.min(3, w / 3.5, h / 3.5);
    return poly([[x + c, y], [x + w - c, y], [x + w, y + c], [x + w, y + h - c], [x + w - c, y + h], [x + c, y + h], [x, y + h - c], [x, y + c]]) + `${rest}/>`;
  });
}
// круги → многоугольники (6 — шестиугольник, 8 — восьмиугольник)
function polygons(body, sides) {
  return body.replace(/<circle cx='([\d.]+)' cy='([\d.]+)' r='([\d.]+)'( class='\w+')?\/>/g, (m, cx, cy, r, cls = "") => {
    [cx, cy, r] = [cx, cy, r].map(Number);
    if (r < 1.6) return m;
    const pts = [];
    for (let i = 0; i < sides; i++) {
      const t = (Math.PI * 2 * i) / sides - Math.PI / 2 + (sides === 8 ? Math.PI / 8 : 0);
      pts.push([cx + r * Math.cos(t), cy + r * Math.sin(t)]);
    }
    return poly(pts) + `${cls}/>`;
  });
}
