const fmt = n => String(Math.round(n * 100) / 100);
// детерминированный шум: одна и та же иконка всегда «дрожит» одинаково
function noise(seed) {
  let s = 0;
  for (const ch of seed) s = (s * 31 + ch.charCodeAt(0)) >>> 0;
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 4294967296 - 0.5;
  };
}
const COUNTS = { m: 2, l: 2, h: 1, v: 1, c: 6, s: 4, q: 4, t: 2, a: 7, z: 0 };
const TOKENS = /[a-zA-Z]|-?(?:\d*\.\d+|\d+\.?)(?:e[-+]?\d+)?/g;
// числа пути с учётом команд: флаги дуг не трогаем
function mapPath(d, fn) {
  let out = "", cmd = "", i = 0;
  for (const tok of d.match(TOKENS) || []) {
    if (/[a-zA-Z]/.test(tok)) {
      cmd = tok;
      i = 0;
      out += tok;
      continue;
    }
    const c = cmd.toLowerCase();
    const k = i++ % (COUNTS[c] || 2);
    const kind = c === "a" ? (k >= 2 && k <= 4 ? "flag" : k < 2 ? "r" : "xy") : "xy";
    const v = kind === "flag" ? tok : fmt(fn(Number(tok), kind));
    out += (/[a-zA-Z]$/.test(out) || String(v).startsWith("-") ? "" : " ") + v;
  }
  return out;
}

/* путь → ломаные (абсолютные точки); res — шаг по длине кривой */
function flattenPath(d, res = 0.6) {
  const lines = [];
  let cur = null, x = 0, y = 0, sx = 0, sy = 0, cmd = "", args = [], pcx = 0, pcy = 0, prev = "";
  const push = (px, py) => cur.push([px, py]);
  const curve = (pts, f) => {
    const len = pts.reduce((a, p, i) => (i ? a + Math.hypot(p[0] - pts[i - 1][0], p[1] - pts[i - 1][1]) : 0), 0);
    const n = Math.max(2, Math.ceil(len / res));
    for (let i = 1; i <= n; i++) push(...f(i / n));
  };
  const arc = (rx, ry, rot, large, sweep, ex, ey) => {
    if (!rx || !ry) return push(ex, ey);
    const phi = (rot * Math.PI) / 180, cos = Math.cos(phi), sin = Math.sin(phi);
    const dx = (x - ex) / 2, dy = (y - ey) / 2;
    const x1 = cos * dx + sin * dy, y1 = -sin * dx + cos * dy;
    let r1 = Math.abs(rx), r2 = Math.abs(ry);
    const lam = (x1 * x1) / (r1 * r1) + (y1 * y1) / (r2 * r2);
    if (lam > 1) { r1 *= Math.sqrt(lam); r2 *= Math.sqrt(lam); }
    const sgn = large === sweep ? -1 : 1;
    const num = r1 * r1 * r2 * r2 - r1 * r1 * y1 * y1 - r2 * r2 * x1 * x1;
    const co = sgn * Math.sqrt(Math.max(0, num / (r1 * r1 * y1 * y1 + r2 * r2 * x1 * x1)));
    const cx1 = (co * r1 * y1) / r2, cy1 = (-co * r2 * x1) / r1;
    const cx = cos * cx1 - sin * cy1 + (x + ex) / 2, cy = sin * cx1 + cos * cy1 + (y + ey) / 2;
    const ang = (ux, uy, vx, vy) => Math.atan2(ux * vy - uy * vx, ux * vx + uy * vy);
    const t1 = ang(1, 0, (x1 - cx1) / r1, (y1 - cy1) / r2);
    let dt = ang((x1 - cx1) / r1, (y1 - cy1) / r2, (-x1 - cx1) / r1, (-y1 - cy1) / r2);
    if (!sweep && dt > 0) dt -= 2 * Math.PI;
    if (sweep && dt < 0) dt += 2 * Math.PI;
    const n = Math.max(2, Math.ceil((Math.abs(dt) * Math.max(r1, r2)) / res));
    for (let i = 1; i <= n; i++) {
      const t = t1 + (dt * i) / n;
      push(cx + r1 * Math.cos(t) * cos - r2 * Math.sin(t) * sin, cy + r1 * Math.cos(t) * sin + r2 * Math.sin(t) * cos);
    }
  };
  for (const tok of d.match(TOKENS) || []) {
    if (/[a-zA-Z]/.test(tok)) {
      cmd = tok;
      args = [];
      if (/[zZ]/.test(tok) && cur) { push(sx, sy); x = sx; y = sy; prev = "z"; }
      continue;
    }
    args.push(Number(tok));
    const c = cmd.toLowerCase(), rel = cmd === c, n = COUNTS[c];
    if (args.length < n) continue;
    const a = args.map((v, i) => (rel && c !== "a" ? v + (i % 2 ? y : x) : v));
    if (c === "a" && rel) { a[5] += x; a[6] += y; }
    if (c === "h") a[0] = rel ? args[0] + x : args[0];
    if (c === "v") a[0] = rel ? args[0] + y : args[0];
    args = [];
    if (c === "m") {
      cur = [[a[0], a[1]]];
      lines.push(cur);
      x = sx = a[0]; y = sy = a[1];
      cmd = rel ? "l" : "L";
    } else if (c === "l") { push(a[0], a[1]); x = a[0]; y = a[1]; }
    else if (c === "h") { push(a[0], y); x = a[0]; }
    else if (c === "v") { push(x, a[0]); y = a[0]; }
    else if (c === "c" || c === "s") {
      let c1x, c1y, c2x, c2y, ex, ey;
      if (c === "c") [c1x, c1y, c2x, c2y, ex, ey] = a;
      else { [c2x, c2y, ex, ey] = a; c1x = /[cs]/.test(prev) ? 2 * x - pcx : x; c1y = /[cs]/.test(prev) ? 2 * y - pcy : y; }
      const x0 = x, y0 = y;
      curve([[x0, y0], [c1x, c1y], [c2x, c2y], [ex, ey]], t => {
        const u = 1 - t;
        return [u * u * u * x0 + 3 * u * u * t * c1x + 3 * u * t * t * c2x + t * t * t * ex, u * u * u * y0 + 3 * u * u * t * c1y + 3 * u * t * t * c2y + t * t * t * ey];
      });
      pcx = c2x; pcy = c2y; x = ex; y = ey;
    } else if (c === "q" || c === "t") {
      let qx, qy, ex, ey;
      if (c === "q") [qx, qy, ex, ey] = a;
      else { [ex, ey] = a; qx = /[qt]/.test(prev) ? 2 * x - pcx : x; qy = /[qt]/.test(prev) ? 2 * y - pcy : y; }
      const x0 = x, y0 = y;
      curve([[x0, y0], [qx, qy], [ex, ey]], t => [(1 - t) ** 2 * x0 + 2 * (1 - t) * t * qx + t * t * ex, (1 - t) ** 2 * y0 + 2 * (1 - t) * t * qy + t * t * ey]);
      pcx = qx; pcy = qy; x = ex; y = ey;
    } else if (c === "a") {
      arc(a[0], a[1], a[2], a[3], a[4], a[5], a[6]);
      x = a[5]; y = a[6];
    }
    prev = c;
  }
  return lines;
}
// все линии рисунка как ломаные
function polylines(body, res) {
  const out = [];
  const num = (el, k) => Number((new RegExp(` ${k}='([^']+)'`).exec(el) || [])[1] || 0);
  for (const el of body.match(/<(rect|circle|ellipse|path)\b[^>]*\/>/g) || []) {
    if (el.startsWith("<path")) out.push(...flattenPath(/d='([^']+)'/.exec(el)[1], res));
    else if (el.startsWith("<rect")) {
      const x = num(el, "x"), y = num(el, "y"), w = num(el, "width"), h = num(el, "height"), r = Math.min(num(el, "rx"), w / 2, h / 2);
      out.push(...flattenPath(r ? `M${x + r} ${y}H${x + w - r}A${r} ${r} 0 0 1 ${x + w} ${y + r}V${y + h - r}A${r} ${r} 0 0 1 ${x + w - r} ${y + h}H${x + r}A${r} ${r} 0 0 1 ${x} ${y + h - r}V${y + r}A${r} ${r} 0 0 1 ${x + r} ${y}z` : `M${x} ${y}h${w}v${h}h${-w}z`, res));
    } else {
      const cx = num(el, "cx"), cy = num(el, "cy"), rx = num(el, "r") || num(el, "rx"), ry = num(el, "r") || num(el, "ry");
      out.push(...flattenPath(`M${cx - rx} ${cy}A${rx} ${ry} 0 1 0 ${cx + rx} ${cy}A${rx} ${ry} 0 1 0 ${cx - rx} ${cy}z`, res));
    }
  }
  return out;
}
const segDist = (px, py, [ax, ay], [bx, by]) => {
  const dx = bx - ax, dy = by - ay, l = dx * dx + dy * dy;
  const t = l ? Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / l)) : 0;
  return Math.hypot(px - ax - t * dx, py - ay - t * dy);
};
// рисунок по сетке: пиксели (квадраты, слитые в полосы) или точки
function rasterize(body, { mode, grid }, sw, solidBody) {
  const lines = polylines(body, grid / 3);
  const fills = solidBody ? polylines(solidBody, grid / 3) : [];
  const n = Math.round(24 / grid);
  const reach = mode === "dot" ? sw * 0.62 + grid * 0.18 : sw / 2 + grid * 0.28;
  const on = [];
  for (let j = 0; j < n; j++) {
    on.push([]);
    for (let i = 0; i < n; i++) {
      const px = (i + 0.5) * grid, py = (j + 0.5) * grid;
      let hit = false;
      for (const l of lines) {
        for (let k = 1; k < l.length && !hit; k++) hit = segDist(px, py, l[k - 1], l[k]) <= reach;
        if (hit) break;
      }
      // залитые места (звезда «в закладках» и т. п.)
      if (!hit) {
        for (const l of fills) {
          let inside = false;
          for (let k = 0, m = l.length - 1; k < l.length; m = k++) {
            const [xi, yi] = l[k], [xj, yj] = l[m];
            if ((yi > py) !== (yj > py) && px < ((xj - xi) * (py - yi)) / (yj - yi) + xi) inside = !inside;
          }
          if (inside) { hit = true; break; }
        }
      }
      on[j].push(hit);
    }
  }
  let out = "";
  for (let j = 0; j < n; j++) {
    for (let i = 0; i < n; i++) {
      if (!on[j][i]) continue;
      if (mode === "dot") {
        out += `<circle cx='${fmt((i + 0.5) * grid)}' cy='${fmt((j + 0.5) * grid)}' r='${fmt(grid * 0.36)}'/>`;
      } else {
        let k = i;
        while (k + 1 < n && on[j][k + 1]) k++;
        out += `<rect x='${fmt(i * grid)}' y='${fmt(j * grid)}' width='${fmt((k - i + 1) * grid)}' height='${fmt(grid)}'/>`;
        i = k;
      }
    }
  }
  return out;
}
// линия от руки: плавно гуляет поперёк хода и заходит за концы
function scribble(body, { wobble, over }, seed) {
  const rnd = noise(seed);
  return polylines(body, 0.7).map(l => {
    if (l.length < 2) return "";
    const closed = l.length > 2 && Math.hypot(l[0][0] - l[l.length - 1][0], l[0][1] - l[l.length - 1][1]) < 0.05;
    const pts = l.slice();
    const ext = (a, b) => {
      const d = Math.hypot(a[0] - b[0], a[1] - b[1]) || 1;
      return [a[0] + ((a[0] - b[0]) / d) * over * (0.5 + rnd() * 0.5), a[1] + ((a[1] - b[1]) / d) * over * (0.5 + rnd() * 0.5)];
    };
    if (over && !closed) {
      pts.unshift(ext(pts[0], pts[1]));
      pts.push(ext(pts[pts.length - 1], pts[pts.length - 2]));
    }
    if (over && closed) pts.push(...pts.slice(1, 3));
    const p1 = rnd() * 6, p2 = rnd() * 6, f1 = 0.8 + rnd() * 0.4, f2 = 2 + rnd() * 0.8;
    let acc = 0;
    const out = pts.map((p, i) => {
      if (i) acc += Math.hypot(p[0] - pts[i - 1][0], p[1] - pts[i - 1][1]);
      const a = pts[Math.max(0, i - 1)], b = pts[Math.min(pts.length - 1, i + 1)];
      let nx = a[1] - b[1], ny = b[0] - a[0];
      const nl = Math.hypot(nx, ny) || 1;
      const d = wobble * (Math.sin(acc * f1 + p1) * 0.6 + Math.sin(acc * f2 + p2) * 0.4);
      return [p[0] + (nx / nl) * d, p[1] + (ny / nl) * d];
    });
    return `<path d='M${out.map(p => p.map(fmt).join(" ")).join("L")}'/>`;
  }).join("");
}
