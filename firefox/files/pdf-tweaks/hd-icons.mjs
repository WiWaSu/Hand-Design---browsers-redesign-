// рамка пути (по опорным точкам) — чтобы понять, какая фигура внутри какой
function pathBox(d) {
  const box = [Infinity, Infinity, -Infinity, -Infinity];
  for (const l of flattenPath(d, 2)) for (const [x, y] of l) {
    box[0] = Math.min(box[0], x); box[1] = Math.min(box[1], y);
    box[2] = Math.max(box[2], x); box[3] = Math.max(box[3], y);
  }
  return box;
}
const shapeBox = el => {
  const n = k => Number((new RegExp(` ${k}='([^']+)'`).exec(el) || [])[1] || 0);
  if (el.startsWith("<rect")) return [n("x"), n("y"), n("x") + n("width"), n("y") + n("height")];
  if (el.startsWith("<circle")) return [n("cx") - n("r"), n("cy") - n("r"), n("cx") + n("r"), n("cy") + n("r")];
  if (el.startsWith("<ellipse")) return [n("cx") - n("rx"), n("cy") - n("ry"), n("cx") + n("rx"), n("cy") + n("ry")];
  return null;
};
