// делит рисунок на «внешние» замкнутые фигуры (их заливаем) и детали (их прорезаем)
function splitParts(body) {
  const closed = [], open = [];
  for (const el of body.match(/<(rect|circle|ellipse|path)\b[^>]*\/>/g) || []) {
    if (/class='(dot|solid)'/.test(el)) continue;
    if (!el.startsWith("<path")) {
      (/stroke-dasharray/.test(el) ? open : closed).push({ el, box: shapeBox(el) });
      continue;
    }
    const d = /d='([^']+)'/.exec(el)[1];
    for (const s of d.match(/[Mm][^Mm]*/g) || []) {
      const piece = `<path d='${s}'/>`;
      (/[zZ]\s*$/.test(s) ? closed : open).push({ el: piece, box: pathBox(s) });
    }
  }
  const outer = closed.filter(p => !closed.some(q => inside(p.box, q.box)));
  const inner = closed.filter(p => !outer.includes(p));
  return { outer: outer.map(p => p.el).join(""), details: [...inner, ...open].map(p => p.el).join("") };
}
